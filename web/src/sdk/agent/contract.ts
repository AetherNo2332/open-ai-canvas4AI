/** Agent wire contracts. No UI state, browser globals or generation requests. */
export const AGENT_CONTRACT_VERSION = "agent-sdk/v1" as const;
export type AgentBusinessScope = { type: string; id: string };
export type AgentPermissionMode = "read_only" | "auto" | "request_approval";
export type AgentCanvasScope = { type: "canvas"; id: string };
export type AgentPlatformScope = { type: "platform"; id: "self" };
export type AgentRunRequestBase = {
    prompt: string;
    agentDefinitionId?: string;
    model?: string;
    logicalModelId?: string;
    channelId?: string;
    channelModelKey?: string;
    reasoningMode?: "off" | "minimal" | "low" | "medium" | "high" | "max" | "auto" | "deep";
    skillIds?: string[];
    focusNodeIds?: string[];
    permissionMode?: AgentPermissionMode;
    contextScope?: string[];
    subagentEnabled?: boolean;
    subagentWriteEnabled?: boolean;
    storyboardDisabled?: boolean;
    budget?: { maxCredits?: number; maxGenerationTasks?: number; maxVideoSeconds?: number; maxSteps?: number };
    idempotencyKey: string;
};
export type AgentCanvasRunRequest = AgentRunRequestBase & {
    scope?: AgentCanvasScope;
    canvasId: string;
    dramaEpisodeId?: never;
};
export type AgentExplicitRunRequest = AgentRunRequestBase & {
    scope: AgentBusinessScope;
    canvasId?: "";
    dramaEpisodeId?: string;
};
export type AgentRunRequest = AgentCanvasRunRequest | AgentExplicitRunRequest;
export type AgentMessageInput = {
    expectedRunId: string;
    mode: "queue" | "interject";
    replyToQuestionId?: string;
    inheritRunConfiguration?: boolean;
    request: AgentRunRequest;
};
export type AgentEvent = {
    eventId: string;
    runId: string;
    seq: number;
    type: string;
    payload: Record<string, unknown>;
    createdAt: string;
};
export type AgentRunSkill = {
    id: string;
    name: string;
    source?: "global" | "user";
    version: string;
    hash: string;
    nativeName?: string;
    versionId?: string;
    versionLabel?: string;
};
export type AgentContextCompactionState = {
    status: "requested" | "running";
    sourceBytes?: number;
    turnCount?: number;
    resume?: boolean;
    projectedTokens?: number;
    usableInputTokens?: number;
    ratio?: number;
    tokenSource?: "provider" | "estimate";
};
export type AgentApprovalSnapshot = {
    approvalId: string;
    decision?: "approve" | "reject";
    reason?: string;
    callHash?: string;
    call?: { id: string; function: { name: string; arguments: string } };
    preview?: { kind: string; title: string; description: string };
};
export type AgentRunSnapshot = {
    contractVersion?: typeof AGENT_CONTRACT_VERSION;
    scope?: AgentBusinessScope;
    agentDefinitionId?: string;
    agentDefinitionVersion?: number;
    dramaEpisodeId?: string;
    rules?: Array<{ source: string; revision: number; text: string }>;
    id: string;
    conversationId?: string;
    parentId?: string;
    canvasId: string;
    userPrompt?: string;
    idempotencyKey?: string;
    status: "queued" | "running" | "waiting_approval" | "completed" | "failed" | "cancelled" | "rejected";
    permissionMode: AgentPermissionMode;
    revision?: number;
    cleanupPending?: boolean;
    failureMessage?: string;
    spentCredits?: number;
    step?: number;
    runtimePhase?: "ready" | "advancing" | "waiting_model" | "waiting_tool" | "waiting_approval" | "waiting_compaction" | "waiting_resource" | "retry_delay" | "terminal";
    waitReason?: string;
    model?: string;
    channelId?: string;
    channelModelKey?: string;
    logicalModelId?: string;
    createdAt: string;
    updatedAt: string;
    skillRuntimeMode?: "pi-native" | "legacy-go";
    skills?: AgentRunSkill[];
    events?: AgentEvent[];
    eventSeqBase?: number;
    latestSeq?: number;
    eventCount?: number;
    eventsTruncated?: boolean;
    activeMessage?: { messageId: string; text: string };
    approval?: AgentApprovalSnapshot;
    contextCompaction?: AgentContextCompactionState;
};
export type AgentRunReceipt<R extends AgentRunSnapshot = AgentRunSnapshot> = { run: R };
export type AgentConversation = {
    id: string;
    canvasId: string;
    title: string;
    latestRunId: string;
    status: AgentRunSnapshot["status"];
    scope: AgentBusinessScope;
    agentDefinitionId: string;
    resumable: boolean;
    archived: boolean;
    revision: number;
    cleanupPending?: boolean;
    queueRevision?: number;
    queuedCount?: number;
    queuePaused?: boolean;
    createdAt: string;
    updatedAt: string;
};
export type AgentConversationPage<T> = { items: T[]; nextCursor?: string };
export type AgentConversationQueue = {
    conversationId: string;
    latestRunId: string;
    canvasId?: string;
    revision: number;
    paused: boolean;
    pauseReason?: string;
    awaitingQuestionId?: string;
    questionRunId?: string;
    items: AgentQueuedMessage[];
};
export type AgentQueuedMessage = {
    id: string;
    conversationId: string;
    canvasId?: string;
    mode: "interject" | "queue";
    sequence: number;
    revision: number;
    prompt: string;
    status: "queued" | "dispatching" | "interjected" | "cancelled" | "failed";
    runId?: string;
    error?: string;
    createdAt: string;
    updatedAt: string;
};
export type AgentUISettings = {
    defaultSendMode: "interject" | "queue";
    revision: number;
};
export type AgentSkillDefaultsSummary = {
    count: number;
    skills: Array<{ skillId: string; skillName: string }>;
};
export type AgentCapabilities = {
    version: number;
    scope?: AgentBusinessScope;
    agentDefinitionId?: string;
    agentDefinitionVersion?: number;
    permissionModes: AgentPermissionMode[];
    contextScopes: string[];
    skills: boolean;
    writeTools: boolean;
    businessTools?: string[];
    tools?: string[];
    defaultSkills?: AgentSkillDefaultsSummary;
    interactionPolicy?: string;
    memoryPolicy?: string;
    availability: { configured: boolean; readyWorkers: number; queueReason: string; reason: string };
    capabilitySetVersion?: string;
    capabilitySetHash?: string;
    nodeTypes?: string[];
    historyPolicy?: "server_compacted";
    contextCompaction?: { enabled: boolean; strategy: "structured_checkpoint"; thresholdBytes: number; thresholdHistoryMessages: number; retainedRecentPairs: number };
    maxHistoryPairs?: number;
    maxHistoryBytes?: number;
    maxSteps?: number;
};
export type AgentRunQuery = {
    sinceSeq?: number;
    eventLimit?: number;
    fromStart?: boolean;
};
export type AgentApprovalDecision = {
    decision: "approve" | "reject";
    reason?: string;
    mediaSettings?: { logicalModelId?: string; channelId?: string; channelModelKey?: string; size: string; quality: string };
};
export type AgentMessageReceipt = {
    messageId: string;
    conversationId: string;
    delivery: "queued" | "started" | "interjected" | "cancelled";
    runId?: string;
    queueRevision: number;
};
